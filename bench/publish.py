#!/usr/bin/env python3
"""Publish a benchmark result: the table between README.md's bench markers and the charts of bench/chart.py.

    python3 bench/publish.py                        # the newest complete CI result in bench/results
    python3 bench/publish.py bench/results/<date>-<commit>.json
    python3 bench/publish.py --check                # exit 1 unless README.md and the charts show that newest result (CI)

Writes bench/summary.svg (the README's chart), bench/per-project-time.svg and bench/per-project-memory.svg
(bench/README.md's), each with a -dark twin. A result is complete when every project has both binaries' wall time and
peak memory; publishing an incomplete one (a failed project) keeps the table and charts as they are.
.github/workflows/bench.yml runs this in its results commit step; `bench/run.py --readme` runs it on the result it
just measured.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
import sys

import chart
import run

REPO = run.REPO
README = REPO / "README.md"
RESULTS = run.BENCH / "results"
# Chart file stem -> the metric of a per-project chart, None for the summary.
CHARTS = {"summary": None, "per-project-time": "wall_s", "per-project-memory": "peak_rss_bytes"}
THEMES = {"light": "", "dark": "-dark"}


def latest() -> Path | None:
    """The newest result measured in CI that is complete (by date, like tools/rule_coverage.py's newest CI result)."""
    best = None
    for path in sorted(RESULTS.glob("*.json")):
        result = json.loads(path.read_text())
        if result.get("machine", {}).get("ci") and chart.complete(result) and (best is None or result["date"] > best[0]):
            best = (result["date"], path)
    return best[1] if best else None


def table(result: dict, result_path: Path) -> str:
    """The README's bench block: one row per project and a one-line caption naming the machine and date."""
    stock = result["stock"]["version"]
    rel = f"bench/results/{result_path.name}"
    lines = [
        f"<!-- Generated by bench/publish.py from {rel}; edit the generator, not this section. -->",
        "",
        "| project | files | tsgolint | tsrslint | faster | tsgolint peak | tsrslint peak | less memory | "
        "differing diagnostics |",
        "| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |",
    ]
    for name, project in result["projects"].items():
        g, t = project["stock"], project["tsrslint"]
        parity = project.get("parity")
        differ = f"{parity['keys_differ']:,} of {int(t['diagnostics']):,}" if parity else "n/a"
        lines.append(
            f"| {chart.project_label(result, name)} | {project['files']:,} | {chart.format_value('wall_s', g['wall_s'])} | "
            f"{chart.format_value('wall_s', t['wall_s'])} | {g['wall_s'] / t['wall_s']:.1f}x | "
            f"{run.fmt_mem(g['peak_rss_bytes'])} | {run.fmt_mem(t['peak_rss_bytes'])} | "
            f"{g['peak_rss_bytes'] / t['peak_rss_bytes']:.1f}x | {differ} |")
    lines += [
        "",
        f"{result['machine']['label']}, {result['date']}. Stock tsgolint {stock} (npm "
        f"`{result['stock']['package']}`) vs tsrslint `{result['tsrslint']['commit'][:12]}` "
        f"({run.TSRSLINT_BUILDS[result['tsrslint']['build']]}), all {result['rules']} rules, wall time and peak RSS, "
        f"{chart.reps_text(result)}. "
        + (f"{chart.PGO_MARK.strip()}: in the PGO training set, which flatters tsrslint there. " if any(
            p.get("pgo_training") for p in result["projects"].values()) else "")
        + f"[All columns]({rel[:-len('.json')]}.md) · [raw measurements]({rel}) · [methodology](bench/README.md)",
    ]
    return "\n".join(lines) + "\n"


def splice(text: str, block: str, readme: Path) -> str:
    if run.START not in text or run.END not in text:
        sys.exit(f"{readme} has no {run.START} ... {run.END} markers")
    before, rest = text.split(run.START, 1)
    _, after = rest.split(run.END, 1)
    return f"{before}{run.START}\n{block}{run.END}{after}"


def render(result_path: Path, readme: Path) -> dict[Path, str] | None:
    """Every file publishing writes and its content, or None when the result is incomplete."""
    result = json.loads(result_path.read_text())
    if not chart.complete(result):
        return None
    files = {readme: splice(readme.read_text(), table(result, result_path), readme)}
    for stem, metric in CHARTS.items():
        for theme, suffix in THEMES.items():
            image = chart.svg(result, theme) if metric is None else chart.per_project_svg(result, metric, theme)
            files[run.BENCH / f"{stem}{suffix}.svg"] = image
    return files


def publish(result_path: Path, readme: Path = README) -> bool:
    # Rendered before anything is written, so a rendering failure cannot leave a mismatched set.
    files = render(result_path, readme)
    if files is None:
        print(f"{result_path.name}: not every project has both binaries' measurements; keeping the published table "
              "and charts.")
        return False
    for path, content in files.items():
        path.write_text(content)
    print(f"Published {result_path.name} to {readme.name} and {len(files) - 1} charts.")
    return True


def check(readme: Path) -> None:
    result_path = latest()
    if result_path is None:
        sys.exit(f"no complete CI result in {RESULTS}")
    stale = [path for path, content in render(result_path, readme).items()
             if not path.exists() or path.read_text() != content]
    if stale:
        sys.exit(f"stale, not {result_path.name}: {', '.join(p.relative_to(REPO).as_posix() for p in stale)}; run "
                 "`python3 bench/publish.py`")
    print(f"{readme.name} and the charts show {result_path.name}")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("result", type=Path, nargs="?", help="result to publish (default: the newest complete CI one)")
    parser.add_argument("--readme", type=Path, default=README, help="README with the bench markers (default: README.md)")
    parser.add_argument("--check", action="store_true", help="exit 1 unless the README table and the charts are current")
    args = parser.parse_args()
    if args.check:
        if args.result:
            parser.error("--check always compares with the newest complete CI result")
        check(args.readme)
        return
    result_path = args.result or latest()
    if result_path is None:
        parser.error(f"no complete CI result in {RESULTS}")
    publish(result_path, args.readme)


if __name__ == "__main__":
    main()
